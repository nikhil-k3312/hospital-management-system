/**
 * Problem 25: creates a 4-validator Hyperledger Besu network with QBFT consensus.
 * With n = 4 validators the network tolerates f = 1 faulty or malicious validator (n >= 3f + 1).
 *
 *   cd blockchain
 *   node besu-qbft/setup.js                 (needs Docker Desktop running)
 *   docker compose -f besu-qbft/docker-compose.yml up -d
 *
 * Optional environment variables:
 *   BESU_IMAGE  Docker image, default hyperledger/besu:24.12.2 (any recent 24.x/25.x tag works)
 *   GOVERNORS   comma-separated administrator wallet addresses to fund (otherwise 3 demo wallets are made)
 *
 * Output (in besu-qbft/generated/, never commit it: it holds private keys):
 *   genesis.json, validator1..4/key, docker-compose.yml (one level up), accounts.json
 */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { ethers } = require('ethers');

const HERE = __dirname;
const OUT = path.join(HERE, 'generated');
const IMAGE = process.env.BESU_IMAGE || 'hyperledger/besu:24.12.2';
const CHAIN_ID = 1337;
const SUBNET = '172.16.240';
const BALANCE = '0x' + (10n ** 24n).toString(16); // 1,000,000 ETH (test value, no real worth)

function run(cmd, args) {
  console.log(`> ${cmd} ${args.join(' ')}`);
  return execFileSync(cmd, args, { stdio: 'inherit' });
}

function main() {
  if (fs.existsSync(OUT)) {
    console.error(`${OUT} already exists. Delete it first to create a new network (all chain data starts again).`);
    process.exit(1);
  }
  fs.mkdirSync(OUT, { recursive: true });

  // 1. accounts: the API's hospital account (deploys contracts, anchors) and the administrators' wallets
  const hospital = ethers.Wallet.createRandom();
  let governors = (process.env.GOVERNORS || '').split(',').map((a) => a.trim()).filter(Boolean).map((address) => ({ address }));
  if (!governors.length) governors = [1, 2, 3].map(() => { const w = ethers.Wallet.createRandom(); return { address: w.address, privateKey: w.privateKey }; });
  const alloc = {};
  [hospital.address, ...governors.map((g) => g.address)].forEach((a) => { alloc[a.slice(2).toLowerCase()] = { balance: BALANCE }; });

  // 2. QBFT genesis + 4 validator keys, generated by Besu itself
  const qbftConfig = {
    genesis: {
      config: {
        chainId: CHAIN_ID,
        londonBlock: 0,
        zeroBaseFee: true, // private network: no fee market
        qbft: { blockperiodseconds: 2, epochlength: 30000, requesttimeoutseconds: 4 },
      },
      nonce: '0x0',
      timestamp: '0x58ee40ba',
      gasLimit: '0x1fffffffffffff',
      difficulty: '0x1',
      mixHash: '0x63746963616c2062797a616e74696e65206661756c7420746f6c6572616e6365',
      coinbase: '0x0000000000000000000000000000000000000000',
      alloc,
    },
    blockchain: { nodes: { generate: true, count: 4 } },
  };
  fs.writeFileSync(path.join(OUT, 'qbftConfigFile.json'), JSON.stringify(qbftConfig, null, 2));
  run('docker', ['run', '--rm', '-v', `${OUT}:/data`, IMAGE, 'operator', 'generate-blockchain-config',
    '--config-file=/data/qbftConfigFile.json', '--to=/data/networkFiles', '--private-key-file-name=key']);

  const keysDir = path.join(OUT, 'networkFiles', 'keys');
  const validators = fs.readdirSync(keysDir).sort().slice(0, 4);
  if (validators.length !== 4) throw new Error(`Expected 4 validator keys, found ${validators.length}`);
  fs.copyFileSync(path.join(OUT, 'networkFiles', 'genesis.json'), path.join(OUT, 'genesis.json'));
  const nodes = validators.map((address, i) => {
    const dir = path.join(OUT, `validator${i + 1}`);
    fs.mkdirSync(dir);
    fs.copyFileSync(path.join(keysDir, address, 'key'), path.join(dir, 'key'));
    const pub = fs.readFileSync(path.join(keysDir, address, 'key.pub'), 'utf8').trim().replace(/^0x/, '');
    return { name: `validator${i + 1}`, address, ip: `${SUBNET}.${11 + i}`, enode: `enode://${pub}@${SUBNET}.${11 + i}:30303` };
  });

  // 3. docker-compose.yml: validator1 exposes the JSON-RPC port 8545 to the laptop; validator2 8546 (spare entry point)
  const service = (n, i) => `  ${n.name}:
    image: ${IMAGE}
    container_name: medichain-${n.name}
    restart: unless-stopped
    command:
      - --data-path=/opt/besu/data
      - --genesis-file=/opt/besu/genesis.json
      - --node-private-key-file=/opt/besu/key
      - --p2p-host=${n.ip}
      - --p2p-port=30303
      - --bootnodes=${nodes.filter((o) => o !== n).map((o) => o.enode).join(',')}
      - --rpc-http-enabled
      - --rpc-http-host=0.0.0.0
      - --rpc-http-port=8545
      - --rpc-http-api=ETH,NET,WEB3,QBFT,TXPOOL
      - --rpc-http-cors-origins=*
      - --host-allowlist=*
      - --min-gas-price=0
    volumes:
      - ./generated/genesis.json:/opt/besu/genesis.json:ro
      - ./generated/${n.name}/key:/opt/besu/key:ro
      - ${n.name}-data:/opt/besu/data
${i < 2 ? `    ports:\n      - "${8545 + i}:8545"\n` : ''}    networks:
      medichain:
        ipv4_address: ${n.ip}
`;
  const compose = `# Generated by besu-qbft/setup.js (Problem 25). 4 QBFT validators; tolerates 1 faulty validator.
services:
${nodes.map(service).join('')}
networks:
  medichain:
    driver: bridge
    ipam:
      config:
        - subnet: ${SUBNET}.0/24

volumes:
${nodes.map((n) => `  ${n.name}-data:`).join('\n')}
`;
  fs.writeFileSync(path.join(HERE, 'docker-compose.yml'), compose);

  const accounts = {
    chainId: CHAIN_ID, rpc: 'http://127.0.0.1:8545',
    hospital: { address: hospital.address, privateKey: hospital.privateKey, use: 'CHAIN_PRIVATE_KEY of the API; deploys the contracts' },
    governors: governors.map((g) => ({ ...g, use: 'administrator wallet: import the private key into MetaMask' })),
    validators: nodes.map(({ name, address, ip }) => ({ name, address, ip })),
  };
  fs.writeFileSync(path.join(OUT, 'accounts.json'), JSON.stringify(accounts, null, 2));

  console.log('\nDone. Next steps:');
  console.log('  docker compose -f besu-qbft/docker-compose.yml up -d');
  console.log('  node besu-qbft/check.js                       (waits until blocks are produced)');
  console.log(`  set CHAIN_PRIVATE_KEY=${hospital.privateKey}`);
  console.log(`  set GOVERNORS=${governors.map((g) => g.address).join(',')}`);
  console.log('  npx hardhat run scripts/deploy.js --network besu');
  console.log('  npx hardhat run scripts/deployRoleRegistry.js --network besu');
  console.log('Keys are in besu-qbft/generated/accounts.json (test network only; keep the folder out of git).');
}

main();
